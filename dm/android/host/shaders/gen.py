#!/usr/bin/env python3
# Compiles the host's own shaders (stretch.vert / stretch.frag) with glslc and writes ../nvn_vk_blit_spv.h. Usage: gen.py <glslc>
import os, struct, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__)); out = []
for name in ('stretch.vert', 'stretch.frag', 'stretch_depth.frag'):
    spv = os.path.join(here, name + '.spv')
    subprocess.run([sys.argv[1], '-O', '--target-env=vulkan1.3', os.path.join(here, name), '-o', spv], check=True)
    b = open(spv, 'rb').read(); os.remove(spv); w = struct.unpack('<%dI' % (len(b) // 4), b)
    var = 'k_' + name.replace('.', '_')
    out.append(f'static const uint32_t {var}[{len(w)}] = {{\n' + ',\n'.join('    ' + ', '.join(f'0x{x:08x}' for x in w[i:i + 8]) for i in range(0, len(w), 8)) + '\n};')
open(os.path.join(here, '..', 'nvn_vk_blit_spv.h'), 'w', newline='\n').write('// Generated by shaders/gen.py from shaders/stretch.vert and stretch.frag: do not edit\n#pragma once\n#include <stdint.h>\n' + '\n'.join(out) + '\n')
print('ok')
