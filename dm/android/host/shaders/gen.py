#!/usr/bin/env python3
# Compiles the host's own shaders (stretch.vert / stretch.frag) with glslc and writes ../nvn_vk_blit_spv.h. Usage: gen.py <glslc>
import os, struct, subprocess, sys
here = os.path.dirname(os.path.abspath(__file__)); out = []
for name in ('stretch.vert', 'stretch.frag', 'stretch_depth.frag'):
    spv = os.path.join(here, name + '.spv')
    subprocess.run([sys.argv[1], '-O', '--target-env=vulkan1.3', os.path.join(here, name), '-o', spv], check=True)
    b = open(spv, 'rb').read(); os.remove(spv); w = struct.unpack('<%dI' % (len(b) // 4), b)
    var = 'k_' + name.replace('.', '_')
    out.append(f'static const uint32_t {var}[{len(w)}] = {{\n' + ',\n'.join('    ' + ', '.join(f'0x{x:08x}' for x in w[i:i + 8]) for i in range(0, len(w), 8)) + '\n};')
open(os.path.join(here, '..', 'nvn_vk_blit_spv.h'), 'w', newline='\n').write('// Generated by shaders/gen.py from shaders/stretch.vert and stretch.frag: do not edit\n#pragma once\n#include <stdint.h>\n' + '\n'.join(out) + '\n')
print('ok')
# the subgroup layout probe (nvn_vk_sgprobe.c), its own header
name = 'sgprobe.comp'; spv = os.path.join(here, name + '.spv')
subprocess.run([sys.argv[1], '--target-env=vulkan1.3', os.path.join(here, name), '-o', spv], check=True)   # not optimized: the reductions stay where they are written
b = open(spv, 'rb').read(); os.remove(spv); w = struct.unpack('<%dI' % (len(b) // 4), b)
open(os.path.join(here, '..', 'nvn_vk_sgprobe_spv.h'), 'w', newline='\n').write('// Generated by shaders/gen.py from shaders/sgprobe.comp: do not edit\n#pragma once\n#include <stdint.h>\n' +
    f'static const uint32_t k_sgprobe_comp[{len(w)}] = {{\n' + ',\n'.join('    ' + ', '.join(f'0x{x:08x}' for x in w[i:i + 8]) for i in range(0, len(w), 8)) + '\n};\n')
print('ok sgprobe')
# the early-depth kick's shaders (nvn_vk_exec.c lrz_kick), their own header
out = []
for name in ('lrz.vert', 'lrz.frag'):
    spv = os.path.join(here, name + '.spv'); subprocess.run([sys.argv[1], '-O', '--target-env=vulkan1.3', os.path.join(here, name), '-o', spv], check=True)
    b = open(spv, 'rb').read(); os.remove(spv); w = struct.unpack('<%dI' % (len(b) // 4), b)
    out.append(f'static const uint32_t k_{name.replace(".", "_")}[{len(w)}] = {{\n' + ',\n'.join('    ' + ', '.join(f'0x{x:08x}' for x in w[i:i + 8]) for i in range(0, len(w), 8)) + '\n};')
open(os.path.join(here, '..', 'nvn_vk_lrz_spv.h'), 'w', newline='\n').write('// Generated by shaders/gen.py from shaders/lrz.vert and lrz.frag: do not edit\n#pragma once\n#include <stdint.h>\n' + '\n'.join(out) + '\n')
print('ok lrz')
# FSR 2's reactive mask (nvn_vk_draw.c reactive_run), its own header
name = 'reactive.comp'; spv = os.path.join(here, name + '.spv')
# Vulkan 1.1 target: for 1.3 this glslc writes the group size as OpExecutionModeId LocalSizeId, which Qualcomm's Adreno 830 driver ran as 8 x 1 (only the top
# eighth of the image was processed: the capture logs_mem3/000944). The 1.1 form is the plain OpExecutionMode LocalSize 8 8 1
subprocess.run([sys.argv[1], '-O', '--target-env=vulkan1.1', os.path.join(here, name), '-o', spv], check=True)
b = open(spv, 'rb').read(); os.remove(spv); w = struct.unpack('<%dI' % (len(b) // 4), b)
open(os.path.join(here, '..', 'nvn_vk_reactive_spv.h'), 'w', newline='\n').write('// Generated by shaders/gen.py from shaders/reactive.comp: do not edit\n#pragma once\n#include <stdint.h>\n' +
    f'static const uint32_t k_reactive_comp[{len(w)}] = {{\n' + ',\n'.join('    ' + ', '.join(f'0x{x:08x}' for x in w[i:i + 8]) for i in range(0, len(w), 8)) + '\n};\n')
print('ok reactive')
